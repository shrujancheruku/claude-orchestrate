"""scripts/transition through its CLI, with the fake `gh`: one verb per stop, hand-back and marker comment (#661).

Each verb is run twice: once against the ticket as it stands, then against the ticket as the first run left it, and the second
run writes nothing. The markers are read back by lead-route in tests/test_lead_route.py (the round trips).
"""

import json
import sys
import tempfile
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from harness import ScriptEnv, gh_repo_view, rest_pull, verdict_runs  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
HEAD = "a" * 40
STOP = "> *Stopped for the lead.*"
ADR = "> *ADR conflict held for the lead.*"
UNDELIVERED = "> *Waiting on lead (not delivered).*"
RESENT = "> *Resent to lead.*"
TRIAGE = "> *This was generated by AI during triage.*"
ISSUE = "repos/{owner}/{repo}/issues/7"


def node(labels=(), comments=()):
    nodes = [{"body": b, "createdAt": f"2026-11-11T10:{i:02d}:00Z", "lastEditedAt": None, "authorAssociation": "OWNER",
              "author": {"login": "dev"}} for i, b in enumerate(comments)]
    return {"number": 7, "title": "t", "url": "u", "state": "OPEN", "body": "b", "authorAssociation": "OWNER",
            "author": {"login": "dev"}, "editor": None, "lastEditedAt": None,
            "labels": {"nodes": [{"name": n} for n in labels]}, "comments": {"totalCount": len(nodes), "nodes": nodes}}


class Transition(unittest.TestCase):
    def setUp(self):
        self.env = verdict_runs(ScriptEnv())
        self.addCleanup(self.env.close)
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        self.tmp = Path(tmp.name)

    def file(self, name, text):
        p = self.tmp / name
        p.write_text(text)
        return str(p)

    def gh(self, labels=(), comments=(), assignees=("dev",), extra=()):
        """Serve the ticket as it stands now, and forget the calls so far: `writes()` then lists the next run's only."""
        Path(str(self.env.gh_state) + ".calls").unlink(missing_ok=True)
        self.env.set_gh([
            gh_repo_view(),
            {"args": ["api", "graphql"], "stdout": json.dumps({"data": {"repository": {"issue": node(labels, comments)}}})},
            {"args": ["api", ISSUE], "stdout": json.dumps({"assignees": [{"login": a} for a in assignees]})},
            {"args": ["api", "--method", "POST", ISSUE + "/comments"], "stdout": '{"html_url": "https://example.test/c/1"}'},
            {"args": ["api", "--method", "POST"], "stdout": "{}"},
            {"args": ["api", "--method", "DELETE"], "stdout": "{}"},
            {"args": ["api", "--method", "PATCH"], "stdout": "{}"},
            *extra])

    def run_t(self, *args, check=True):
        return self.env.run("transition", *args, "--repo", ".", check=check)

    def writes(self):
        """[(method, path suffix, fields)] for every write the run made."""
        out = []
        for c in self.env.gh_calls():
            if c[:2] in (["api", "--method"],) and c[2] in ("POST", "DELETE", "PATCH"):
                fields = [a.split("=", 1) for a in c[4:] if "=" in a and not a.startswith("-")]
                out.append((c[2], c[3].replace("repos/{owner}/{repo}/", ""), dict(fields)))
        return out

    def comments(self):
        return [f["body"] for m, p, f in self.writes() if p.endswith("/comments")]

    def verdict(self, r):
        return r.verdict

    # --- stop-for-lead -------------------------------------------------------------------------------------------

    def test_stop_for_lead_labels_and_posts_the_stop_comment_then_a_repeat_writes_nothing(self):
        q = self.file("q.md", "Which value should it be?\n")
        self.gh(labels=["ready-for-agent"])
        r = self.run_t("stop-for-lead", 7, "--question-file", q, "--branch", "7-x")
        self.assertEqual(self.verdict(r), "next: transitioned stop-for-lead 7")
        (body,) = self.comments()
        self.assertEqual(body, f"{STOP}\n\nWhich value should it be?\n\nBranch: `7-x`")
        self.assertIn("commented: #7 " + STOP + " https://example.test/c/1", r.stdout)  # the URL for the nudge
        self.assertIn(("POST", "issues/7/labels", {"labels[]": "needs-lead"}), self.writes())

    def test_a_repeated_stop_for_lead_posts_and_labels_nothing(self):
        q = self.file("q.md", "Which value?")
        body = f"{STOP}\n\nWhich value?\n\nBranch: `7-x`"
        self.gh(labels=["needs-lead"], comments=[body])
        r = self.run_t("stop-for-lead", 7, "--question-file", q, "--branch", "7-x")
        self.assertEqual(self.verdict(r), "next: unchanged stop-for-lead 7")
        self.assertEqual(self.writes(), [])

    def test_the_same_question_after_the_lead_answered_is_a_new_stop(self):
        q = self.file("q.md", "Which value?")
        body = f"{STOP}\n\nWhich value?\n\nBranch: `7-x`"
        self.gh(labels=[], comments=[body, "Use 3."])  # the lead removed needs-lead
        r = self.run_t("stop-for-lead", 7, "--question-file", q, "--branch", "7-x")
        self.assertEqual(self.verdict(r), "next: transitioned stop-for-lead 7")
        self.assertEqual(self.comments(), [body])

    def test_a_mention_in_the_question_is_defused_and_a_long_one_is_cut_with_a_count(self):
        q = self.file("q.md", "ping @someone and @org/team please " + "x" * 5000)
        self.gh()
        self.run_t("stop-for-lead", 7, "--question-file", q, "--branch", "7-x")
        (body,) = self.comments()
        self.assertNotIn("@s", body)
        self.assertIn("@​someone", body)
        self.assertRegex(body, r"\[cut: \d+ more characters\]")
        self.assertLess(len(body), 4300)

    def test_an_empty_or_missing_question_file_is_refused_with_nothing_written(self):
        self.gh()
        for path in (self.file("empty.md", "  \n"), str(self.tmp / "missing.md")):
            r = self.run_t("stop-for-lead", 7, "--question-file", path, "--branch", "7-x", check=False)
            self.assertEqual(r.returncode, 1)
            self.assertTrue(self.verdict(r).startswith("next: ask-user "))
        self.assertEqual(self.writes(), [])

    def transition_events(self):
        return [e for e in self.env.events() if e["kind"] == "transition"]

    def test_stop_for_lead_adr_hold_and_to_info_each_write_a_transition_event(self):
        q = self.file("q.md", "Which?")
        self.gh()
        self.run_t("stop-for-lead", 7, "--question-file", q, "--branch", "7-x")
        self.run_t("adr-hold", 7, "--pr", "9", "--conflicts-file", q)
        self.run_t("to-info", 7, "--question-file", q)
        self.assertEqual([(e["outcome"], e["ref"]) for e in self.transition_events()],
                         [("stop-for-lead", 7), ("adr-hold", 7), ("to-info", 7)])
        self.assertEqual(self.transition_events()[0]["branch"], "7-x")
        self.assertEqual(self.transition_events()[1]["pr"], 9)

    def test_a_refused_call_and_the_other_verbs_write_no_transition_event(self):
        self.gh()
        self.run_t("stop-for-lead", 7, "--question-file", str(self.tmp / "missing.md"), "--branch", "7-x", check=False)
        self.run_t("resent", 7, "--head", HEAD)
        self.assertEqual(self.transition_events(), [])

    def test_claims_reads_the_wait_a_transition_wrote(self):
        import claims
        import runlog
        q = self.file("q.md", "Which?")
        self.gh()
        for verb, extra, label, reason in (("stop-for-lead", ["--question-file", q, "--branch", "7-x"], "needs-lead", "question"),
                                           ("adr-hold", ["--pr", "9", "--conflicts-file", q], "needs-lead", "adr-conflict"),
                                           ("to-info", ["--question-file", q], "needs-info", "info")):
            with self.subTest(verb=verb):
                self.run_t(verb, 7, *extra)
                events = runlog.read_kinds(self.env.repo, claims.CLAIM_EVENT_KINDS)
                self.assertEqual(claims._transition_wait(events, 7, {label})[0], reason)

    # --- adr-hold ------------------------------------------------------------------------------------------------

    def test_adr_hold_posts_the_conflicts_and_the_pr_and_repeats_quietly(self):
        c = self.file("c.md", "ADR-0011 forbids this.")
        self.gh()
        r = self.run_t("adr-hold", 7, "--pr", 12, "--conflicts-file", c)
        self.assertEqual(self.verdict(r), "next: transitioned adr-hold 7")
        (body,) = self.comments()
        self.assertEqual(body, f"{ADR}\n\nADR-0011 forbids this.\n\nPR #12")
        self.gh(labels=["needs-lead"], comments=[body])
        r = self.run_t("adr-hold", 7, "--pr", 12, "--conflicts-file", c)
        self.assertEqual(self.verdict(r), "next: unchanged adr-hold 7")

    # --- undelivered and resent ----------------------------------------------------------------------------------

    def test_undelivered_names_the_full_head_and_dedupes_per_head(self):
        g = self.file("g.md", "ci: test failed")
        self.gh()
        r = self.run_t("undelivered", 7, "--head", HEAD, "--gist-file", g)
        self.assertEqual(self.verdict(r), "next: transitioned undelivered 7")
        (body,) = self.comments()
        self.assertEqual(body, f"{UNDELIVERED}\n\nhead {HEAD}\n\nci: test failed")
        self.gh(comments=[body])
        self.assertEqual(self.verdict(self.run_t("undelivered", 7, "--head", HEAD, "--gist-file", g)),
                         "next: unchanged undelivered 7")
        self.assertEqual(self.writes(), [])
        self.gh(comments=[body])  # a push is a new head, so a new failure
        r = self.run_t("undelivered", 7, "--head", "b" * 40, "--gist-file", g)
        self.assertEqual(self.verdict(r), "next: transitioned undelivered 7")

    def test_a_short_or_non_hex_head_is_refused_and_writes_nothing(self):
        g = self.file("g.md", "x")
        self.gh()
        for head in ("abc1234", "A" * 40, "g" * 40, HEAD + "0"):
            for verb, extra in (("undelivered", ["--gist-file", g]), ("resent", [])):
                with self.subTest(verb=verb, head=head):
                    r = self.run_t(verb, 7, "--head", head, *extra, check=False)
                    self.assertEqual(r.returncode, 1)
                    self.assertRegex(self.verdict(r), r"^next: ask-user --head must be the full 40-character")
        self.assertEqual(self.writes(), [])

    def test_resent_comments_once_per_head(self):
        self.gh()
        r = self.run_t("resent", 7, "--head", HEAD)
        self.assertEqual(self.verdict(r), "next: transitioned resent 7")
        (body,) = self.comments()
        self.assertEqual(body, f"{RESENT}\n\nhead {HEAD}")
        self.gh(comments=[body, "later chatter"])
        r = self.run_t("resent", 7, "--head", HEAD)
        self.assertEqual((self.verdict(r), self.writes()), ("next: unchanged resent 7", []))

    # --- to-human and to-info ------------------------------------------------------------------------------------

    def test_to_human_swaps_the_state_label_unassigns_and_comments_the_branch(self):
        q = self.file("q.md", "Needs a credential only you have.")
        self.gh(labels=["ready-for-agent"])
        r = self.run_t("to-human", 7, "--question-file", q, "--branch", "7-x")
        self.assertEqual(self.verdict(r), "next: transitioned to-human 7")
        writes = self.writes()
        self.assertIn(("POST", "issues/7/labels", {"labels[]": "ready-for-human"}), writes)
        self.assertIn(("DELETE", "issues/7/labels/ready-for-agent", {}), writes)
        self.assertIn(("DELETE", "issues/7/assignees", {"assignees[]": "dev"}), writes)
        (body,) = self.comments()
        self.assertEqual(body, f"{TRIAGE}\n\nNeeds a credential only you have.\n\nBranch: `7-x`")
        self.gh(labels=["ready-for-human"], comments=[body], assignees=())
        r = self.run_t("to-human", 7, "--question-file", q, "--branch", "7-x")
        self.assertEqual((self.verdict(r), self.writes()), ("next: unchanged to-human 7", []))

    def test_to_info_uses_needs_info_and_no_branch_line_without_a_branch(self):
        q = self.file("q.md", "Which of the two?")
        self.gh(labels=["ready-for-agent"])
        r = self.run_t("to-info", 7, "--question-file", q)
        self.assertEqual(self.verdict(r), "next: transitioned to-info 7")
        self.assertIn(("POST", "issues/7/labels", {"labels[]": "needs-info"}), self.writes())
        self.assertEqual(self.comments(), [f"{TRIAGE}\n\nWhich of the two?"])

    # --- fallback ------------------------------------------------------------------------------------------------

    def test_fallback_swaps_needs_lead_for_needs_info_comments_and_unassigns(self):
        self.gh(labels=["needs-lead", "ready-for-agent"], comments=[f"{STOP}\n\nq"])
        r = self.run_t("fallback", 7)
        self.assertEqual(self.verdict(r), "next: transitioned fallback 7")
        writes = self.writes()
        self.assertIn(("POST", "issues/7/labels", {"labels[]": "needs-info"}), writes)
        self.assertIn(("DELETE", "issues/7/labels/needs-lead", {}), writes)
        self.assertIn(("DELETE", "issues/7/assignees", {"assignees[]": "dev"}), writes)
        (body,) = self.comments()
        self.assertTrue(body.startswith(TRIAGE) and "lead is gone" in body)
        self.gh(labels=["needs-info", "ready-for-agent"], comments=[body], assignees=())
        r = self.run_t("fallback", 7)
        self.assertEqual((self.verdict(r), self.writes()), ("next: unchanged fallback 7", []))

    # --- abandon -------------------------------------------------------------------------------------------------

    def pull(self, state="open", branch="7-x"):
        return {"args": ["api", "repos/{owner}/{repo}/pulls/12"], "stdout": json.dumps(
            rest_pull(state=state.upper(), headRefName=branch, headRefOid=HEAD))}

    def test_abandon_closes_the_pr_keeps_the_branch_and_unassigns(self):
        self.gh(extra=[self.pull()])
        r = self.run_t("abandon", 7, "--pr", 12)
        self.assertEqual(self.verdict(r), "next: transitioned abandon 7")
        self.assertIn("closed: PR #12", r.stdout)
        writes = self.writes()
        self.assertIn(("PATCH", "pulls/12", {"state": "closed"}), writes)
        self.assertIn(("DELETE", "issues/7/assignees", {"assignees[]": "dev"}), writes)
        self.assertFalse([w for w in writes if "git/refs" in w[1] or "branches" in w[1]])  # the branch is kept

    def test_abandon_of_an_already_closed_pr_and_unassigned_ticket_writes_nothing(self):
        self.gh(assignees=(), extra=[self.pull(state="closed")])
        r = self.run_t("abandon", 7, "--pr", 12)
        self.assertEqual((self.verdict(r), self.writes()), ("next: unchanged abandon 7", []))

    def test_abandon_refuses_a_pr_that_is_not_the_tickets(self):
        self.gh(extra=[self.pull(branch="9-other")])
        r = self.run_t("abandon", 7, "--pr", 12, check=False)
        self.assertEqual(r.returncode, 1)
        self.assertIn("not a branch of #7", self.verdict(r))
        self.assertEqual(self.writes(), [])

    def test_abandon_with_no_pr_just_unassigns(self):
        self.gh()
        r = self.run_t("abandon", 7)
        self.assertEqual(self.verdict(r), "next: transitioned abandon 7")
        self.assertEqual([w[1] for w in self.writes()], ["issues/7/assignees"])

    # --- handback ------------------------------------------------------------------------------------------------

    def test_handback_unassigns_comments_the_branch_and_blockers_and_runs_the_rescue(self):
        self.gh()
        r = self.run_t("handback", 7, "--branch", "7-x", "--pr", 12, "--blocked-by", 3, 5, "--title", "t")
        self.assertEqual(self.verdict(r), "next: transitioned handback 7")
        (body,) = self.comments()
        self.assertEqual(body, f"{TRIAGE}\n\nHanded back: the work is on branch `7-x` (PR #12, left open).\nWaiting on: #3, #5.")
        self.assertIn("rescue: nothing to rescue: no worktree on 7-x", r.stdout)  # the rescue's own lines are passed on
        self.assertIn(("DELETE", "issues/7/assignees", {"assignees[]": "dev"}), self.writes())

    def test_a_repeated_handback_posts_no_second_comment(self):
        self.gh()
        self.run_t("handback", 7, "--branch", "7-x")
        (body,) = self.comments()
        self.gh(comments=[body], assignees=())
        r = self.run_t("handback", 7, "--branch", "7-x")
        self.assertEqual(self.writes(), [])
        self.assertEqual(self.verdict(r), "next: transitioned handback 7")  # the rescue ran again; it is the idempotent step

    # --- usage ---------------------------------------------------------------------------------------------------

    def test_a_flag_the_verb_does_not_take_or_a_missing_one_is_a_usage_error(self):
        self.gh()
        for args in (("fallback", 7, "--branch", "7-x"), ("handback", 7), ("resent", 7), ("stop-for-lead", 7, "--branch", "b"),
                     ("nonsense", 7)):
            with self.subTest(args=args):
                r = self.env.run("transition", *args, "--repo", ".", check=False)
                self.assertEqual(r.returncode, 2)
                self.assertEqual(self.writes(), [])

    def test_no_marker_string_appears_in_a_prompt(self):
        # The markers are written by this script and read by lead-route; a prompt that typed one could misspell it (#661).
        sys.path.insert(0, str(ROOT / "scripts"))
        import tracker
        markers = [getattr(tracker, n) for n in dir(tracker) if n.endswith("_MARKER")]
        self.assertGreaterEqual(len(markers), 6)
        for path in sorted([*ROOT.glob("skills/**/*.md"), *ROOT.glob("agents/*.md")]):
            text = path.read_text()
            for m in markers:
                self.assertFalse(m in text, f"{path.relative_to(ROOT)} restates the marker {m!r}")

    def test_the_wire_strings_are_the_ones_lead_route_has_always_read(self):
        sys.path.insert(0, str(ROOT / "scripts"))
        import tracker
        self.assertEqual((tracker.STOP_MARKER, tracker.ADR_MARKER, tracker.UNDELIVERED_MARKER, tracker.RESENT_MARKER,
                          tracker.TRIAGE_MARKER, tracker.RISK_MARKER),
                         (STOP, ADR, UNDELIVERED, RESENT, TRIAGE, "> *Risk notes (review not posted).*"))


